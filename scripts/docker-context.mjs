import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { sourceIdentity } from './source-identity.mjs';

/** Exact file exceptions keep local projects, reports, credentials and ignored
 * implementation files out of the context sent to a local or remote builder. */
export function dockerIgnoreFor(paths) {
  const files = [...new Set([...paths, '.dockerignore'])].sort();
  for (const file of files) {
    if (!file || file.trim() !== file || file.startsWith('/') || file.split('/').some(part => !part || part === '.' || part === '..') || /[\r\n\\*?!\[\]#]/.test(file))
      throw new Error(`Unsupported literal Docker context path: ${JSON.stringify(file)}`);
  }
  return '# Generated by npm run container:context; checked by container:check.\n' +
    '# Allow only the public build inputs. Do not add broad directory exceptions.\n**\n' +
    files.map(file => `!${file}`).join('\n') + '\n';
}

export function assertContainerToolchain(dockerfile, pkg) {
  const node = dockerfile.match(/^FROM node:([^@\s]+)@sha256:[a-f0-9]{64} AS build$/m);
  if (node?.[1] !== `${pkg.engines.node}-bookworm-slim` ||
      !dockerfile.includes(`RUN npm install --global npm@${pkg.engines.npm}\n`) ||
      !/^FROM nginx\/nginx-unprivileged:\d+\.\d+\.\d+-alpine@sha256:[a-f0-9]{64} AS runtime$/m.test(dockerfile))
    throw new Error('Container base digests and Node/npm pins must match the supported toolchain.');
}

export function checkDockerContext(root = process.cwd(), write = false) {
  const expected = dockerIgnoreFor(sourceIdentity(root).inputs.map(input => input.path));
  assertContainerToolchain(readFileSync(resolve(root, 'Dockerfile'), 'utf8'), JSON.parse(readFileSync(resolve(root, 'package.json'))));
  if (write) writeFileSync(resolve(root, '.dockerignore'), expected);
  else if (readFileSync(resolve(root, '.dockerignore'), 'utf8') !== expected)
    throw new Error('Docker context inventory changed. Run npm run container:context and review .dockerignore.');
  return expected;
}

if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) {
  if (process.argv.length !== 3 || !['--check', '--write'].includes(process.argv[2]))
    throw new Error('Usage: node scripts/docker-context.mjs --check|--write');
  checkDockerContext(process.cwd(), process.argv[2] === '--write');
  console.log(`Docker context ${process.argv[2] === '--write' ? 'updated' : 'verified'}; exact files only.`);
}
